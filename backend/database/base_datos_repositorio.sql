CREATE OR REPLACE PROCEDURE sp_resolver_solicitud_patente(
  p_id BIGINT, p_codigo_coordinador BIGINT,
  p_resultado VARCHAR, p_motivo TEXT DEFAULT NULL
)
LANGUAGE plpgsql AS $$
DECLARE
  v_solicitud solicitud_patente%ROWTYPE;
  v_inventores BIGINT[];
  v_campos_ocde VARCHAR[];
  v_objetivos_ocde VARCHAR[];
  v_snapshot JSONB;
BEGIN
  SELECT * INTO v_solicitud
    FROM solicitud_patente
   WHERE id = p_id
   FOR UPDATE;
  IF NOT FOUND OR v_solicitud.estado <> 'pendiente_revision' THEN
    RAISE EXCEPTION 'La solicitud de patente no existe o no está pendiente.';
  END IF;
  IF p_resultado IS NULL
     OR p_resultado NOT IN ('aprobada', 'observada', 'rechazada') THEN
    RAISE EXCEPTION 'Resultado de revisión de patente no válido.';
  END IF;
  IF p_resultado <> 'aprobada' AND COALESCE(btrim(p_motivo), '') = '' THEN
    RAISE EXCEPTION 'Indique el motivo de la observación o rechazo.';
  END IF;
  IF NOT EXISTS (
    SELECT 1 FROM coordinador_repositorios
     WHERE codigo_ucsm = p_codigo_coordinador AND fecha_retiro IS NULL
  ) THEN
    RAISE EXCEPTION 'El coordinador no existe o ya fue retirado.';
  END IF;

  SELECT ARRAY_AGG(codigo_ucsm ORDER BY codigo_ucsm)
    INTO v_inventores
    FROM solicitud_patente_investigador
   WHERE solicitud_patente_id = p_id;
  SELECT ARRAY_AGG(campo_ocde ORDER BY campo_ocde),
         ARRAY_AGG(objetivo_ocde ORDER BY campo_ocde)
    INTO v_campos_ocde, v_objetivos_ocde
    FROM solicitud_patente_ocde
   WHERE solicitud_patente_id = p_id;
  IF COALESCE(cardinality(v_inventores), 0) = 0
     OR NOT (v_solicitud.solicitante_codigo_ucsm = ANY (v_inventores)) THEN
    RAISE EXCEPTION 'La solicitud debe incluir al solicitante como inventor.';
  END IF;
  IF COALESCE(cardinality(v_campos_ocde), 0) = 0
     OR cardinality(v_campos_ocde) <> cardinality(v_objetivos_ocde) THEN
    RAISE EXCEPTION 'La solicitud requiere pares completos de campo y objetivo OCDE.';
  END IF;

  v_snapshot := jsonb_build_object(
    'solicitante_codigo_ucsm', v_solicitud.solicitante_codigo_ucsm,
    'n_patente', v_solicitud.n_patente,
    'titulo_patente', v_solicitud.titulo_patente,
    'editorial', v_solicitud.editorial,
    'fecha_registro', v_solicitud.fecha_registro,
    'cip', v_solicitud.cip,
    'pais', v_solicitud.pais,
    'inventores', to_jsonb(v_inventores),
    'campos_ocde', to_jsonb(v_campos_ocde),
    'objetivos_ocde', to_jsonb(v_objetivos_ocde)
  );

  IF p_resultado = 'aprobada' THEN
    CALL sp_registrar_patente(
      v_solicitud.n_patente, v_solicitud.titulo_patente,
      v_solicitud.editorial, v_solicitud.fecha_registro,
      v_solicitud.cip, v_solicitud.pais, p_codigo_coordinador,
      v_inventores, v_campos_ocde, v_objetivos_ocde
    );
    UPDATE formato_patente
       SET solicitud_patente_id = p_id
     WHERE n_patente = v_solicitud.n_patente;
  END IF;

  INSERT INTO revision_solicitud (
    solicitud_patente_id, version_evaluada, resultado, datos_evaluados,
    motivo, resuelto_por
  )
  VALUES (
    p_id, v_solicitud.version_actual, p_resultado, v_snapshot,
    NULLIF(btrim(p_motivo), ''), p_codigo_coordinador
  );
  UPDATE solicitud_patente
     SET estado = p_resultado, actualizada_en = CURRENT_TIMESTAMP
   WHERE id = p_id;
END; $$;

