-- 1.2.1 Cuenta, postulacion y verificaciones del investigador
-- Cuentas de acceso al portal. Una sola tabla para los dos roles con cuenta
-- propia: investigador (postulante) y administrador (mantenimiento técnico).
-- El coordinador conserva su tabla original coordinador_repositorios.
CREATE TABLE cuenta_usuario (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  rol VARCHAR(15) NOT NULL DEFAULT 'investigador',
  dni CHAR(8) UNIQUE,
  codigo_ucsm BIGINT UNIQUE,
  nombre VARCHAR(120),
  correo_elec VARCHAR(100) NOT NULL,
  password_hash VARCHAR(255) NOT NULL,
  estado_cuenta VARCHAR(12) NOT NULL DEFAULT 'activa',
  creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT ck_cuenta_usuario_rol
    CHECK (rol IN ('investigador', 'administrador')),
  CONSTRAINT ck_cuenta_usuario_datos_rol
    CHECK (
      (rol = 'investigador' AND dni IS NOT NULL AND codigo_ucsm IS NOT NULL)
      OR (rol = 'administrador' AND COALESCE(btrim(nombre), '') <> '')
    ),
  CONSTRAINT ck_cuenta_investigador_dni
    CHECK (dni ~ '^[0-9]{8}$'),
  CONSTRAINT ck_cuenta_investigador_codigo
    CHECK (codigo_ucsm BETWEEN 1000000000 AND 9999999999),
  CONSTRAINT ck_cuenta_investigador_correo
    CHECK (correo_elec LIKE '%_@_%._%'),
  CONSTRAINT ck_cuenta_investigador_estado
    CHECK (estado_cuenta IN ('activa', 'bloqueada')),
  CONSTRAINT ck_cuenta_usuario_hash
    CHECK (password_hash LIKE 'pbkdf2_sha256$%')
);

