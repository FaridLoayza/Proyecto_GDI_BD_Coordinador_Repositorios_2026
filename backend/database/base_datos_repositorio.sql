CREATE OR REPLACE PROCEDURE sp_resolver_solicitud_investigador(
  p_id BIGINT, p_codigo_coordinador BIGINT,
  p_resultado VARCHAR, p_motivo TEXT DEFAULT NULL
)
LANGUAGE plpgsql AS $$
DECLARE
  v_solicitud solicitud_investigador%ROWTYPE;
  v_cuenta cuenta_investigador%ROWTYPE;
  v_version_id BIGINT;
  v_ods VARCHAR[];
  v_intereses VARCHAR[];
BEGIN
  SELECT * INTO v_solicitud
    FROM solicitud_investigador
   WHERE id = p_id
   FOR UPDATE;
  IF NOT FOUND OR v_solicitud.estado <> 'pendiente_revision' THEN
    RAISE EXCEPTION 'La solicitud no existe o no está pendiente de revisión.';
  END IF;
  IF p_resultado IS NULL OR p_resultado NOT IN ('aprobada', 'rechazada') THEN
    RAISE EXCEPTION 'El resultado debe ser aprobada o rechazada.';
  END IF;
  IF p_resultado = 'rechazada' AND COALESCE(btrim(p_motivo), '') = '' THEN
    RAISE EXCEPTION 'Indique el motivo del rechazo.';
  END IF;
  IF NOT EXISTS (
    SELECT 1 FROM coordinador_repositorios
     WHERE codigo_ucsm = p_codigo_coordinador AND fecha_retiro IS NULL
  ) THEN
    RAISE EXCEPTION 'El coordinador no existe o ya fue retirado.';
  END IF;

  SELECT * INTO v_cuenta
    FROM cuenta_investigador
   WHERE id = v_solicitud.cuenta_investigador_id;
  SELECT id INTO v_version_id
    FROM solicitud_investigador_version
   WHERE solicitud_id = p_id
     AND numero_version = v_solicitud.version_actual;

  IF p_resultado = 'aprobada' THEN
    v_ods := ARRAY(
      SELECT ods FROM solicitud_investigador_ods
       WHERE solicitud_id = p_id ORDER BY ods
    );
    v_intereses := ARRAY(
      SELECT interes FROM solicitud_investigador_interes
       WHERE solicitud_id = p_id ORDER BY interes
    );
    CALL sp_registrar_investigador(
      v_cuenta.dni::VARCHAR, v_solicitud.nombres,
      v_solicitud.apellido_paterno, v_solicitud.apellido_materno,
      v_solicitud.genero, v_solicitud.fecha_nacimiento,
      v_cuenta.codigo_ucsm, v_solicitud.escuela_profesional,
      v_solicitud.n_celular, v_cuenta.correo_elec,
      v_solicitud.codigo_orcid, v_solicitud.scopus_id,
      v_solicitud.link_cti_vitae, v_solicitud.resumen_academico,
      v_solicitud.foto_referencia, p_codigo_coordinador,
      v_ods, v_intereses
    );
    UPDATE investigador
       SET cuenta_investigador_id = v_cuenta.id,
           pure_estado = 'pendiente_manual'
     WHERE codigo_ucsm = v_cuenta.codigo_ucsm;
  END IF;

  INSERT INTO revision_solicitud
    (solicitud_id, version_id, resultado, motivo, resuelto_por)
  VALUES (p_id, v_version_id, p_resultado, NULLIF(btrim(p_motivo), ''), p_codigo_coordinador);
  UPDATE solicitud_investigador
     SET estado = p_resultado, actualizado_en = CURRENT_TIMESTAMP
   WHERE id = p_id;
END; $$;

CREATE OR REPLACE PROCEDURE sp_registrar_verificacion_solicitud(
  p_solicitud_id BIGINT, p_version INTEGER, p_fuente VARCHAR,
  p_metodo VARCHAR, p_resultado VARCHAR, p_coordinador BIGINT,
  p_referencia VARCHAR, p_nota TEXT
)
LANGUAGE plpgsql AS $$
DECLARE
  v_version_id BIGINT;
BEGIN
  IF p_metodo IS NULL OR p_fuente IS NULL OR p_resultado IS NULL
     OR p_metodo NOT IN ('manual', 'api')
     OR p_fuente NOT IN (
       'codigo_ucsm', 'afiliacion', 'orcid', 'scopus', 'cti_vitae', 'renacyt'
     )
     OR p_resultado NOT IN (
       'confirmado', 'no_confirmado', 'no_disponible',
       'error_consulta', 'requiere_revision'
     ) THEN
    RAISE EXCEPTION 'Los datos de verificación no son válidos.';
  END IF;
  IF p_metodo = 'api' AND p_fuente NOT IN ('orcid', 'scopus') THEN
    RAISE EXCEPTION 'Solo ORCID y Scopus admiten verificaciones por API.';
  END IF;
  IF p_metodo = 'manual' AND NOT EXISTS (
    SELECT 1 FROM coordinador_repositorios
     WHERE codigo_ucsm = p_coordinador AND fecha_retiro IS NULL
  ) THEN
    RAISE EXCEPTION 'La verificación manual requiere un coordinador activo.';
  END IF;

  SELECT id INTO v_version_id
    FROM solicitud_investigador_version
   WHERE solicitud_id = p_solicitud_id
     AND numero_version = p_version;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'La versión indicada de la solicitud no existe.';
  END IF;
  INSERT INTO verificacion_solicitud (
    solicitud_id, version_id, fuente, metodo, resultado, verificado_por,
    referencia_evidencia, nota
  )
  VALUES (
    p_solicitud_id, v_version_id, p_fuente, p_metodo, p_resultado,
    CASE WHEN p_metodo = 'manual' THEN p_coordinador ELSE NULL END,
    p_referencia, p_nota
  );
END; $$;

