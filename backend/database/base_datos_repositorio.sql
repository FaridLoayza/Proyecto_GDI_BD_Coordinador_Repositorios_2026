           s.foto_referencia, s.version_actual, s.enviada_en, s.creado_en AS creada_en,
           COALESCE((SELECT array_agg(o.ods ORDER BY o.ods)
                       FROM solicitud_investigador_ods o WHERE o.solicitud_id = s.id), '{}') AS ods,
