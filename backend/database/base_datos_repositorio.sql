CREATE OR REPLACE PROCEDURE sp_crear_solicitud_patente(
  p_solicitante BIGINT, p_n_patente VARCHAR, p_titulo VARCHAR,
  p_editorial VARCHAR, p_fecha_registro DATE, p_cip VARCHAR, p_pais VARCHAR,
  p_inventores BIGINT[], p_campos_ocde VARCHAR[], p_objetivos_ocde VARCHAR[]
)
LANGUAGE plpgsql AS $$
DECLARE
  v_solicitud_id BIGINT;
  v_inventores_registrados BIGINT;
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM investigador WHERE codigo_ucsm = p_solicitante
  ) THEN
    RAISE EXCEPTION 'Solo un investigador con perfil local puede solicitar una patente.';
  END IF;
  IF COALESCE(cardinality(p_inventores), 0) = 0
     OR NOT (p_solicitante = ANY (p_inventores)) THEN
    RAISE EXCEPTION 'La solicitud debe incluir al solicitante como inventor.';
  END IF;
  IF COALESCE(cardinality(p_campos_ocde), 0) = 0
     OR cardinality(p_campos_ocde) <> cardinality(p_objetivos_ocde) THEN
    RAISE EXCEPTION 'Indique pares completos de campo y objetivo OCDE.';
  END IF;
  SELECT COUNT(DISTINCT fi.codigo_ucsm) INTO v_inventores_registrados
    FROM formato_investigador fi
   WHERE fi.codigo_ucsm = ANY (p_inventores);
  IF v_inventores_registrados <> (
    SELECT COUNT(DISTINCT x) FROM unnest(p_inventores) AS x
  ) THEN
    RAISE EXCEPTION 'Todos los inventores deben tener un perfil local aprobado.';
  END IF;

  INSERT INTO solicitud_patente (
    solicitante_codigo_ucsm, n_patente, titulo_patente, editorial,
    fecha_registro, cip, pais
  )
  VALUES (
    p_solicitante, p_n_patente, p_titulo, p_editorial,
    p_fecha_registro, p_cip, p_pais
  )
  RETURNING id INTO v_solicitud_id;
  INSERT INTO solicitud_patente_investigador (solicitud_patente_id, codigo_ucsm)
    SELECT v_solicitud_id, x FROM unnest(p_inventores) AS x;
  INSERT INTO solicitud_patente_ocde
    (solicitud_patente_id, campo_ocde, objetivo_ocde)
    SELECT v_solicitud_id, t.campo, t.objetivo
      FROM unnest(p_campos_ocde, p_objetivos_ocde) AS t(campo, objetivo);
END; $$;

CREATE OR REPLACE PROCEDURE sp_actualizar_solicitud_patente(
