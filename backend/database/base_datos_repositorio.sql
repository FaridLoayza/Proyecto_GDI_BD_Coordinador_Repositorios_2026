                || ' ' || i.codigo_ucsm::text) ILIKE '%' || p_filtro || '%')
       AND (p_estado = 'todos' OR i.activo = (p_estado = 'activos'))
     ORDER BY pe.apellido_paterno, pe.apellido_materno, pe.nombres;
