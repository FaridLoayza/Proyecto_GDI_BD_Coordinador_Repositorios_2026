-- Migración: cuenta de administrador del portal (tabla 43).
--
-- Se ejecuta UNA vez contra una base ya instalada; es idempotente.
-- Las instalaciones nuevas (instalar_bd.py) ya crean esta tabla.
-- Después, cree la cuenta con:  python backend/database/crear_admin.py
--
-- Ejemplo (Windows):
--   "C:\Program Files\PostgreSQL\16\bin\psql.exe" -U postgres ^
--     -d bd_coordinador_repositorios -f backend\database\migracion_cuenta_administrador.sql

BEGIN;

-- Cuenta técnica de mantenimiento del portal (CRUD sobre los datos).
-- No participa en el flujo investigador/coordinador. Se crea con
-- backend/database/crear_admin.py; no hay contraseña por defecto.
CREATE TABLE IF NOT EXISTS cuenta_administrador (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  correo_elec VARCHAR(100) NOT NULL,
  nombre VARCHAR(120) NOT NULL,
  password_hash VARCHAR(255) NOT NULL,
  activo BOOLEAN NOT NULL DEFAULT TRUE,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT ck_cuenta_administrador_correo
    CHECK (correo_elec LIKE '%_@_%._%'),
  CONSTRAINT ck_cuenta_administrador_nombre
    CHECK (btrim(nombre) <> ''),
  CONSTRAINT ck_cuenta_administrador_hash
    CHECK (password_hash LIKE 'pbkdf2_sha256$%')
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_cuenta_administrador_correo
  ON cuenta_administrador (lower(correo_elec));

COMMIT;
